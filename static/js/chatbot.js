// Skiné AI Multimodal Chatbot Controller (Production Web App)

document.addEventListener('DOMContentLoaded', () => {
    const launcher = document.getElementById('skineChatLauncher');
    const card = document.getElementById('skineChatCard');
    const minimizeBtn = document.getElementById('skineChatMinimize');
    const maximizeBtn = document.getElementById('skineChatMaximize');
    const maximizeIcon = document.getElementById('skineChatMaximizeIcon');
    const resetBtn = document.getElementById('skineChatReset');
    const body = document.getElementById('skineChatBody');
    const input = document.getElementById('skineChatInput');
    const sendBtn = document.getElementById('skineChatSend');
    const chipBtns = document.querySelectorAll('.chat-chip-btn');

    const fileInput = document.getElementById('skineChatFileInput');
    const uploadBtn = document.getElementById('skineChatUploadBtn');
    const previewBar = document.getElementById('skineChatImagePreview');
    const previewThumb = document.getElementById('skineChatPreviewThumb');
    const removeImageBtn = document.getElementById('skineChatRemoveImageBtn');

    const resizeCorner = document.getElementById('skineChatResizeCorner');
    const resizeTop = document.getElementById('skineChatResizeTop');
    const resizeLeft = document.getElementById('skineChatResizeLeft');
    const grabBar = document.getElementById('skineChatGrabBar');

    if (!launcher || !card) return;

    let isLoading = false;
    let isMaximized = false;
    let currentWidth = 450;
    let currentHeight = 630;
    let attachedImage = null;
    let messages = [];

    // Get user info and latest scan data from DOM data attributes
    const isAuth = card.getAttribute('data-auth') === 'true';
    const userName = card.getAttribute('data-user-name') || 'Member';
    const skinType = card.getAttribute('data-skin-type') || 'Combination';
    const score = card.getAttribute('data-score') || '90';

    // Initial message
    if (isAuth) {
        messages.push({
            role: 'model',
            content: `Hello **${userName}**, welcome to Skiné AI.\n\nI have loaded your personalized skin scan data.\n\nYou may ask me about active ingredient compatibility, routine sequencing, paste product labels, or request direct product store links.\n\n*Disclaimer: Responses are generated by AI for informational guidance only and are not 100% accurate. For medical diagnoses, please consult a certified dermatologist.*`,
            time: 'Just now'
        });
        renderMessages();
    }

    // Toggle open/close
    launcher.addEventListener('click', () => {
        card.classList.remove('d-none');
        launcher.classList.add('d-none');
        scrollToBottom();
        setTimeout(() => input && input.focus(), 150);
    });

    if (minimizeBtn) {
        minimizeBtn.addEventListener('click', () => {
            card.classList.add('d-none');
            launcher.classList.remove('d-none');
        });
    }

    // Maximize / Restore Toggle
    if (maximizeBtn) {
        maximizeBtn.addEventListener('click', () => {
            isMaximized = !isMaximized;
            if (isMaximized) {
                card.classList.add('is-maximized');
                card.style.width = 'min(820px, calc(100vw - 36px))';
                card.style.height = 'min(860px, calc(100vh - 48px))';
                if (maximizeIcon) {
                    maximizeIcon.className = 'fa-solid fa-compress';
                }
                if (grabBar) grabBar.classList.add('d-none');
            } else {
                card.classList.remove('is-maximized');
                card.style.width = `${currentWidth}px`;
                card.style.height = `${currentHeight}px`;
                if (maximizeIcon) {
                    maximizeIcon.className = 'fa-solid fa-expand';
                }
                if (grabBar) grabBar.classList.remove('d-none');
            }
            scrollToBottom();
        });
    }

    // Interactive Drag-to-Resize Handlers
    function setupResize(handleEl, direction) {
        if (!handleEl) return;

        handleEl.addEventListener('mousedown', (e) => {
            e.preventDefault();
            const startX = e.clientX;
            const startY = e.clientY;
            const startW = card.offsetWidth;
            const startH = card.offsetHeight;

            function onMouseMove(moveEvent) {
                const deltaX = startX - moveEvent.clientX; // Drag left = wider
                const deltaY = startY - moveEvent.clientY; // Drag up = taller

                if (direction === 'nw' || direction === 'w') {
                    const newW = Math.min(Math.max(340, startW + deltaX), window.innerWidth - 36);
                    currentWidth = newW;
                    card.style.width = `${newW}px`;
                }

                if (direction === 'nw' || direction === 'n') {
                    const newH = Math.min(Math.max(420, startH + deltaY), window.innerHeight - 50);
                    currentHeight = newH;
                    card.style.height = `${newH}px`;
                }

                if (isMaximized) {
                    isMaximized = false;
                    card.classList.remove('is-maximized');
                    if (maximizeIcon) maximizeIcon.className = 'fa-solid fa-expand';
                    if (grabBar) grabBar.classList.remove('d-none');
                }
            }

            function onMouseUp() {
                window.removeEventListener('mousemove', onMouseMove);
                window.removeEventListener('mouseup', onMouseUp);
            }

            window.addEventListener('mousemove', onMouseMove);
            window.addEventListener('mouseup', onMouseUp);
        });
    }

    setupResize(resizeCorner, 'nw');
    setupResize(resizeTop, 'n');
    setupResize(resizeLeft, 'w');
    setupResize(grabBar, 'n');

    // Clipboard Paste Image Listener
    card.addEventListener('paste', (e) => {
        const items = e.clipboardData?.items;
        if (!items) return;
        for (let i = 0; i < items.length; i++) {
            if (items[i].type.indexOf('image') !== -1) {
                const file = items[i].getAsFile();
                if (file) {
                    const reader = new FileReader();
                    reader.onload = (event) => {
                        setAttachedImage(event.target.result);
                    };
                    reader.readAsDataURL(file);
                    e.preventDefault();
                    break;
                }
            }
        }
    });

    // File input trigger
    if (uploadBtn && fileInput) {
        uploadBtn.addEventListener('click', () => fileInput.click());
        fileInput.addEventListener('change', (e) => {
            const file = e.target.files?.[0];
            if (file) {
                const reader = new FileReader();
                reader.onload = (event) => {
                    setAttachedImage(event.target.result);
                };
                reader.readAsDataURL(file);
            }
            e.target.value = '';
        });
    }

    if (removeImageBtn) {
        removeImageBtn.addEventListener('click', () => {
            setAttachedImage(null);
        });
    }

    function setAttachedImage(imgDataUrl) {
        attachedImage = imgDataUrl;
        if (previewBar && previewThumb) {
            if (imgDataUrl) {
                previewThumb.src = imgDataUrl;
                previewBar.classList.remove('d-none');
            } else {
                previewThumb.src = '';
                previewBar.classList.add('d-none');
            }
        }
        scrollToBottom();
    }

    if (resetBtn) {
        resetBtn.addEventListener('click', () => {
            messages = [{
                role: 'model',
                content: `Welcome back, **${userName}**. I am ready to assist with your skincare inquiries for **${skinType}** skin.\n\n*Disclaimer: AI-generated responses are for informational guidance and are not 100% accurate.*`,
                time: 'Just now'
            }];
            renderMessages();
        });
    }

    // Suggested chip clicks
    chipBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const promptText = btn.textContent.trim();
            if (promptText && !isLoading) {
                sendMessage(promptText);
            }
        });
    });

    // Input handlers
    if (input) {
        input.addEventListener('keydown', (e) => {
            if (e.key === 'Enter' && !e.shiftKey) {
                e.preventDefault();
                sendMessage();
            }
        });
    }

    if (sendBtn) {
        sendBtn.addEventListener('click', () => sendMessage());
    }

    async function sendMessage(textOverride) {
        const text = textOverride || (input ? input.value.trim() : '');
        if ((!text && !attachedImage) || isLoading) return;

        if (!isAuth) {
            window.location.href = '/login';
            return;
        }

        const now = new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
        const currentImg = attachedImage;
        messages.push({
            role: 'user',
            content: text || 'Analyze attached product image',
            image: currentImg,
            time: now
        });

        if (input) input.value = '';
        setAttachedImage(null);
        renderMessages();

        isLoading = true;
        showTypingIndicator();

        try {
            const res = await fetch('/api/chat', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'Accept': 'application/json'
                },
                body: JSON.stringify({
                    message: text,
                    image: currentImg,
                    history: messages.map(m => ({ role: m.role, content: m.content })),
                    context: {
                        skin_type: skinType,
                        overall_score: parseFloat(score) || 90.0
                    }
                })
            });

            removeTypingIndicator();

            if (res.status === 401) {
                window.location.href = '/login';
                return;
            }

            const data = await res.json();
            if (data.success) {
                messages.push({
                    role: 'model',
                    content: data.reply,
                    time: new Date().toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
                });
            } else {
                messages.push({
                    role: 'model',
                    content: data.message || 'The AI service is temporarily unavailable. Please retry your inquiry.',
                    time: 'Just now'
                });
            }
        } catch (err) {
            removeTypingIndicator();
            messages.push({
                role: 'model',
                content: 'Network connection interrupted. Please re-submit your inquiry.',
                time: 'Just now'
            });
        } finally {
            isLoading = false;
            renderMessages();
        }
    }

    function formatMarkdown(text) {
        if (!text) return '';
        const lines = text.split('\n');
        return lines.map(line => {
            const trimmed = line.trim();
            if (!trimmed) return '<div style="height:4px;"></div>';

            if (trimmed.startsWith('### ') || trimmed.startsWith('## ')) {
                const headerText = trimmed.replace(/^#{2,3}\s*/, '');
                return `<div class="fw-bold mt-2 mb-1" style="font-size:0.94rem;">${headerText}</div>`;
            }

            // Markdown Links [Text](URL) -> Clickable <a target="_blank">
            let formatted = trimmed.replace(
                /\[([^\]]+)\]\((https?:\/\/[^\s\)]+)\)/g,
                '<a href="$2" target="_blank" rel="noopener noreferrer" class="chat-external-link"><i class="fa-solid fa-arrow-up-right-from-square me-1"></i>$1</a>'
            );

            // Bold
            formatted = formatted.replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>');

            // Bullets
            if (trimmed.startsWith('• ') || trimmed.startsWith('- ') || trimmed.startsWith('* ')) {
                const cleanItem = formatted.replace(/^[•\-\*]\s*/, '');
                return `<li class="mb-1" style="margin-left:16px;">${cleanItem}</li>`;
            }

            return `<p class="mb-1">${formatted}</p>`;
        }).join('');
    }

    function renderMessages() {
        if (!body) return;
        body.innerHTML = '';

        messages.forEach((msg, idx) => {
            const row = document.createElement('div');
            row.className = `chat-message-row ${msg.role === 'user' ? 'user-row' : 'bot-row'}`;

            if (msg.role === 'model') {
                row.innerHTML = `
                    <div class="bot-avatar-mini">
                        <i class="fa-solid fa-wand-magic-sparkles"></i>
                    </div>
                    <div class="chat-bubble bot-bubble">
                        <div class="chat-text-content">${formatMarkdown(msg.content)}</div>
                        <div class="d-flex align-items-center justify-content-between mt-2 pt-2 border-top border-opacity-10 gap-2">
                            <button class="chat-copy-btn" data-copy-idx="${idx}">
                                <i class="fa-regular fa-copy"></i>
                                <span class="ms-1 copy-label">Copy</span>
                            </button>
                            <div class="chat-time-tag ms-auto">${msg.time}</div>
                        </div>
                    </div>
                `;
            } else {
                let imgMarkup = '';
                if (msg.image) {
                    imgMarkup = `
                        <div class="chat-msg-img-container mb-2">
                            <img src="${msg.image}" alt="Uploaded photo" class="chat-msg-img" />
                        </div>
                    `;
                }
                row.innerHTML = `
                    <div class="chat-bubble user-bubble">
                        ${imgMarkup}
                        <div class="chat-text-content">${formatMarkdown(msg.content)}</div>
                        <div class="chat-time-tag text-end mt-1">${msg.time}</div>
                    </div>
                `;
            }
            body.appendChild(row);
        });

        // Add copy event listeners
        body.querySelectorAll('.chat-copy-btn').forEach(btn => {
            btn.addEventListener('click', () => {
                const idx = parseInt(btn.getAttribute('data-copy-idx'), 10);
                if (messages[idx]) {
                    navigator.clipboard.writeText(messages[idx].content);
                    const label = btn.querySelector('.copy-label');
                    const icon = btn.querySelector('i');
                    if (label) label.textContent = 'Copied';
                    if (icon) {
                        icon.className = 'fa-regular fa-check text-success';
                    }
                    setTimeout(() => {
                        if (label) label.textContent = 'Copy';
                        if (icon) icon.className = 'fa-regular fa-copy';
                    }, 2000);
                }
            });
        });

        scrollToBottom();
    }

    function showTypingIndicator() {
        if (!body) return;
        const typingEl = document.createElement('div');
        typingEl.id = 'chatTypingIndicator';
        typingEl.className = 'chat-message-row bot-row';
        typingEl.innerHTML = `
            <div class="bot-avatar-mini">
                <i class="fa-solid fa-wand-magic-sparkles"></i>
            </div>
            <div class="chat-bubble bot-bubble typing-bubble">
                <span class="typing-dot"></span>
                <span class="typing-dot"></span>
                <span class="typing-dot"></span>
            </div>
        `;
        body.appendChild(typingEl);
        scrollToBottom();
    }

    function removeTypingIndicator() {
        const typingEl = document.getElementById('chatTypingIndicator');
        if (typingEl) typingEl.remove();
    }

    function scrollToBottom() {
        if (body) {
            body.scrollTop = body.scrollHeight;
        }
    }
});
